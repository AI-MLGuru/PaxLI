from enum import StrEnum


class AuditEventType(StrEnum):
    SESSION_CREATED = "SESSION_CREATED"
    SESSION_RETRIEVED = "SESSION_RETRIEVED"
    EVIDENCE_UPLOADED = "EVIDENCE_UPLOADED"
    EVIDENCE_RETRIEVED = "EVIDENCE_RETRIEVED"
    SESSION_CANCELLED = "SESSION_CANCELLED"
    SESSION_EXPIRED = "SESSION_EXPIRED"
    # WF-001 §13: four specific lifecycle-transition events, not one
    # generic SESSION_LIFECYCLE_TRANSITIONED -- matches the existing
    # vocabulary's granularity (every other lifecycle event above is
    # already specific).
    SESSION_CAPTURING_STARTED = "SESSION_CAPTURING_STARTED"
    SESSION_SUBMITTED = "SESSION_SUBMITTED"
    SESSION_PROCESSING_STARTED = "SESSION_PROCESSING_STARTED"
    SESSION_COMPLETED = "SESSION_COMPLETED"
    CREDENTIAL_ISSUED = "CREDENTIAL_ISSUED"
    CREDENTIAL_ROTATED = "CREDENTIAL_ROTATED"
    CREDENTIAL_REVOKED = "CREDENTIAL_REVOKED"
    AUTHENTICATION_FAILED = "AUTHENTICATION_FAILED"
    AUTHORIZATION_DENIED = "AUTHORIZATION_DENIED"
    EVIDENCE_RESULT_CREATED = "EVIDENCE_RESULT_CREATED"
    EVIDENCE_RESULT_SUPERSEDED = "EVIDENCE_RESULT_SUPERSEDED"
    POLICY_ACTIVATED = "POLICY_ACTIVATED"
    POLICY_ACTIVATION_FAILED = "POLICY_ACTIVATION_FAILED"
    CREDENTIAL_OPERATION_FAILED = "CREDENTIAL_OPERATION_FAILED"
    EVIDENCE_DELETION_REQUESTED = "EVIDENCE_DELETION_REQUESTED"
    EVIDENCE_DELETED = "EVIDENCE_DELETED"
    EVIDENCE_RESULT_DELETION_REQUESTED = "EVIDENCE_RESULT_DELETION_REQUESTED"
    EVIDENCE_RESULT_DELETED = "EVIDENCE_RESULT_DELETED"
    DECISION_PRODUCED = "DECISION_PRODUCED"
    DECISION_ENGINE_FAILED = "DECISION_ENGINE_FAILED"


class AuditActorType(StrEnum):
    CLIENT = "CLIENT"
    SYSTEM = "SYSTEM"
    WORKER = "WORKER"


class AuditStatus(StrEnum):
    SUCCESS = "SUCCESS"
    FAILURE = "FAILURE"


class AuditDurability(StrEnum):
    REQUIRED = "REQUIRED"
    BEST_EFFORT = "BEST_EFFORT"


UNATTRIBUTED_TENANT_ID = "_unattributed"
"""Sentinel `tenant_id` for a required audit event whose action never
resolved to a real tenant (e.g. an authentication attempt with no parseable
or existing credential) -- `audit_events.tenant_id` is non-nullable, and
there is no real tenant to attribute the event to."""
